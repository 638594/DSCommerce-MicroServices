-- Etapa 7a: estrutura do banco do order-service.
-- client_id e product_id são só números: o cliente e o produto moram em OUTROS bancos,
-- por isso não existe FOREIGN KEY para eles.

CREATE TABLE tb_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moment         TIMESTAMP WITH TIME ZONE,
    client_id      BIGINT,
    status         VARCHAR(30),
    payment_moment TIMESTAMP WITH TIME ZONE
);

CREATE TABLE tb_order_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT,
    product_name VARCHAR(255),
    price        NUMERIC(38, 2),
    quantity     INTEGER,
    order_id     BIGINT REFERENCES tb_order (id)
);

-- Índice para o GET /orders, que busca "WHERE client_id = ?"
CREATE INDEX idx_order_client_id ON tb_order (client_id);
