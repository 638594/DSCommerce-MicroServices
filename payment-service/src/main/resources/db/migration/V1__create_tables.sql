-- Etapa 7a: estrutura do banco do payment-service.

CREATE TABLE tb_payment (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- UNIQUE: no máximo um pagamento por pedido (proteção contra mensagem repetida)
    order_id BIGINT UNIQUE,
    amount   NUMERIC(38, 2),
    moment   TIMESTAMP WITH TIME ZONE
);
