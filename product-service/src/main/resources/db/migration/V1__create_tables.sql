-- Etapa 7a: estrutura do banco do product-service.
-- Os nomes de tabela e coluna seguem o que o Hibernate espera das entidades
-- (camelCase vira snake_case: imgUrl -> img_url).

CREATE TABLE tb_category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE tb_product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    description TEXT,
    price       NUMERIC(38, 2),
    img_url     VARCHAR(255)
);

-- Tabela de ligação do @ManyToMany entre produto e categoria
CREATE TABLE tb_product_category (
    product_id  BIGINT NOT NULL REFERENCES tb_product (id),
    category_id BIGINT NOT NULL REFERENCES tb_category (id),
    PRIMARY KEY (product_id, category_id)
);
